/**
 * 本文の Markdown で、改行の印「\」が文字のまま出てしまう形を直す。
 * 入力欄（tiptap-markdown）は段落の中の改行を「\」+ 改行で保存するが、
 * - 改行のあとが空白（全角スペース・nbsp など）だけで段落が終わる
 * - 見出しの中に改行がある
 * と、読み込み直したときに「\」がそのまま本文に出る（外部のエディタからの貼り付けで起きやすい）。
 * 保存する前と、保存済みの本文を表示する前の両方で通す。コードブロックの中は変えない
 */
export function repairMarkdownHardBreaks(md: string): string {
  return md
    .split(/(```[\s\S]*?```)/)
    .map((part, index) => {
      if (index % 2 === 1) return part
      return (
        part
          // 改行の印のあとが空白だけの行（または本文の終わり）なら、印を消して普通の改行にする
          .replace(/(?<!\\)\\\n[ \t 　]*(?=\n|$)/g, "\n")
          // 見出しの行末の改行の印は、見出しの区切りにする
          .replace(/^(#{1,6} .*?)(?<!\\)\\$/gm, "$1")
      )
    })
    .join("")
}
