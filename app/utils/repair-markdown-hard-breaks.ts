/**
 * 本文の Markdown で、改行の印「\」が文字のまま出てしまう形を直す。
 * 入力欄（tiptap-markdown）は段落の中の改行を「\」+ 改行で保存するが、
 * - 改行のあとが空白（全角スペース・nbsp など）だけで段落が終わる
 * - 見出しの中に改行がある
 * と、読み込み直したときに「\」がそのまま本文に出る（外部のエディタからの貼り付けで起きやすい）。
 * また、改行のすぐあとの行が「---」「===」だけだと、その段落全体が見出し（太字の大きい文字）として
 * 読み込まれてしまう（Markdown の「下線で書く見出し」）。その行は文字のまま「\---」にして読み込ませる。
 * 改行の印の前に残った見えない空白（&nbsp;・半角スペース・タブ）も消す。ほかのエディタから貼り付けると
 * 改行のたびに nbsp が残り、行間が広がったり空行が増えたように見える（Discord d さんの報告）。
 * 保存済みの本文には、本文ファイルの保存先（text-uploader）が改行をすべて「空白 2 つ + 改行」に、
 * 行頭の空白を nbsp に書き換えたものがある。その名残も読み込む前に直す
 * - 「\」+ 空白 2 つ以上 + 改行（改行の印のあとに空白が足された）→ 改行の印に戻す（「\」が文字として出ていた）
 * - nbsp だけの行（段落の間の空白だけの行がもう一度書き換えられたもの）→ 空の行（段落の区切り）に戻す
 *   （そのままだと文字の行として読まれ、すべての改行のあとに空行が増えたように見えていた）
 * 保存する前と、保存済みの本文を表示する前の両方で通す。コードブロックの中は変えない
 */
export function repairMarkdownHardBreaks(md: string): string {
  return md
    .split(/(```[\s\S]*?```)/)
    .map((part, index) => {
      if (index % 2 === 1) return part
      return (
        part
          // 改行の印のあとに足された空白を消す（「\\」は文字の「\」なので、行末の「\」の数が奇数のときだけ）
          .replace(/(?<!\\)((?:\\\\)*)\\ {2,}(?=\n|$)/g, "$1\\")
          // nbsp だけの行は空の行にする
          .replace(/^[ \t]*\u00a0[ \t\u00a0]*$/gm, "")
          // 改行の印の前の見えない空白（nbsp・半角スペース・タブ）は、改行のたびに残って増えるので消す
          .replace(/[ \t ]+(?=\\\n)/g, "")
          // 改行の印のあとが空白だけの行（または本文の終わり）なら、印を消して普通の改行にする
          .replace(/(?<!\\)\\\n[ \t  　]*(?=\n|$)/g, "\n")
          // 見出しの行末の改行の印は、見出しの区切りにする
          .replace(/^(#{1,6} .*?)(?<!\\)\\$/gm, "$1")
          // 改行（「\」または行末の 2 つ以上の空白）のすぐあとの「---」「===」だけの行は、文字のままにする
          // （見出しの行のあとの「---」は区切り線なので変えない）
          .replace(
            /^(.*(?:(?<!\\)\\|\S {2,})\n {0,3})(-+|=+)(?=[ \t]*$)/gm,
            (match, before: string, line: string) =>
              /^ {0,3}#{1,6}(?:[ \t]|$)/.test(before)
                ? match
                : `${before}\\${line}`,
          )
      )
    })
    .join("")
}
